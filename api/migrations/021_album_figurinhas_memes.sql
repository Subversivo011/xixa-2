SET LOCAL lock_timeout = '5s';

-- 1) Memes Icônicos -> moedas
DROP TABLE IF EXISTS pg_temp._retirada;
CREATE TEMP TABLE _retirada ON COMMIT DROP AS
SELECT i.usuario_id, i.carta_id,
       i.quantidade * COALESCE((SELECT (valor ->> c.raridade)::int FROM regras_economia WHERE chave = 'valor_repetida'),
         (('{"Comum":5,"Relevante":10,"Raro":20,"Relíquia":40,"Lendário":80,"Mítico":150}'::jsonb) ->> c.raridade)::int, 0) AS valor
  FROM inventario_cartas i JOIN cartas c ON c.id = i.carta_id
 WHERE c.colecao_id = 'memes' AND i.quantidade > 0;

INSERT INTO movimentos_moeda (usuario_id, valor, motivo, ref)
SELECT usuario_id, valor, 'colecao_retirada', carta_id FROM _retirada WHERE valor > 0;

UPDATE usuarios u SET moedas = u.moedas + t.total
  FROM (SELECT usuario_id, sum(valor)::int AS total FROM _retirada GROUP BY usuario_id) t
 WHERE u.id = t.usuario_id AND t.total > 0;

DELETE FROM inventario_cartas WHERE carta_id IN (SELECT id FROM cartas WHERE colecao_id = 'memes');
DELETE FROM cartas WHERE colecao_id = 'memes';
UPDATE pacotes_estoque SET colecao_id = NULL WHERE colecao_id = 'memes';
UPDATE pacotes_abertos SET colecao_id = NULL WHERE colecao_id = 'memes';
DELETE FROM colecoes WHERE id = 'memes';


